function computeStreaks(days) {
	if (!days.length) return {
		current: 0,
		longest: 0,
		total: 0
	};
	const sorted = [...days].sort((a, b) => a.date.localeCompare(b.date));
	let longest = 0;
	let run = 0;
	for (const d of sorted) if (d.count > 0) {
		run += 1;
		if (run > longest) longest = run;
	} else run = 0;
	let current = 0;
	for (let i = sorted.length - 1; i >= 0; i--) if (sorted[i].count > 0) current += 1;
	else break;
	const total = sorted.reduce((s, d) => s + d.count, 0);
	return {
		current,
		longest,
		total
	};
}
